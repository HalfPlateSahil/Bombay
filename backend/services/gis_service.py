def generate_3d_buildings_geojson() -> Dict[str, Any]:
    features = []
    minLat, maxLat, minLon, maxLon = 18.90, 19.28, 72.80, 72.98
    latStep, lonStep = 0.00035, 0.00035
    bldg_id = 1

    for lat in [minLat + i * latStep for i in range(int((maxLat - minLat) / latStep))]:
        for lon in [minLon + j * lonStep for j in range(int((maxLon - minLon) / lonStep))]:
            if lon < 72.812 and lat < 18.96: continue
            if lon < 72.805 and 18.96 <= lat < 19.05: continue
            if lon < 72.800 and lat >= 19.05: continue

            w, h = 0.00025, 0.00025
            poly = [
                [lon - w, lat - h],
                [lon + w, lat - h],
                [lon + w, lat + h],
                [lon - w, lat + h],
                [lon - w, lat - h]
            ]
            baseH, maxH = 25, 75
            if lat < 19.03 and lon < 72.84: baseH, maxH = 50, 260
            elif 19.04 <= lat <= 19.08 and 72.82 <= lon <= 72.88: baseH, maxH = 40, 140
            elif 19.10 <= lat <= 19.16 and 72.82 <= lon <= 72.92: baseH, maxH = 35, 150

            bHeight = baseH + int((math.sin(bldg_id * 1.7) + 1.0) * 0.5 * (maxH - baseH))
            features.append({
                "type": "Feature",
                "id": f"bldg_{bldg_id}",
                "properties": {
                    "id": bldg_id,
                    "name": f"Mumbai Structure #{bldg_id}",
                    "height": bHeight,
                    "min_height": 0,
                    "levels": max(3, int(bHeight / 3.2))
                },
                "geometry": {"type": "Polygon", "coordinates": [poly]}
            })
            bldg_id += 1

    return {"type": "FeatureCollection", "features": features}

